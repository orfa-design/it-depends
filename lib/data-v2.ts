export function lcFirst(str: string): string {
  return str ? str.charAt(0).toLowerCase() + str.slice(1) : str;
}

export function genTask(step: Step, prev?: string): string {
  const title = lcFirst(step.title);
  const used = lcFirst(step.usedWhen.replace(/\.$/, ""));
  const doable = lcFirst((step.doable || "").replace(/\.$/, ""));
  const tool = step.toolName || step.tool;
  const pool = [
    `Хочу ${title} — і зробити це сьогодні, не відкладаючи.`,
    `Маю реальну задачу: ${used}. Допоможи розібратись, з чого почати.`,
    `Треба ${title}. Працюю з ${tool} і хочу швидкий результат.`,
    `Зараз ${used} — хочу спробувати зробити це за один підхід.`,
    `Беруся за те, щоб ${title}. Поясни покроково, ніби я роблю вперше.`,
    `Моя ситуація: ${used}. Хочу зробити це акуратно й без зайвого.`,
    doable ? `Хочу ${doable} — для живого проєкту, не навчальний приклад.` : `Хочу ${title} — і одразу перевірити результат.`,
    `Потрібно ${title}. Дай чіткий план, з чого почати й що далі.`,
  ];
  let pick = prev;
  let guard = 0;
  while (pick === prev && guard < 12) {
    pick = pool[Math.floor(Math.random() * pool.length)];
    guard++;
  }
  return pick || pool[0];
}
